#!/usr/bin/env python3
"""
Insert images into PowerPoint slides based on a mapping JSON file.

This script adds images to specified slides at specified positions,
enabling automated image insertion into presentations generated by
the PPTX skill's template-based workflow.

Usage:
    python insert_images.py <input_pptx> <image_mapping_json> <output_pptx>

Example:
    python insert_images.py working.pptx image-mapping.json final.pptx

Image Mapping JSON Format:
{
  "slides": [
    {
      "slide_number": 5,
      "images": [
        {
          "path": "figures/diagram.png",
          "left": 6.5,
          "top": 1.5,
          "width": 6.0,
          "height": null
        }
      ]
    }
  ]
}

Position/size values are in inches. If width or height is null,
the aspect ratio is preserved based on the other dimension.
If both are null, the original image size is used.

Preset Positions:
Instead of specifying left/top/width/height, you can use preset positions:
  - "right_half": Image fills right half of slide
  - "left_half": Image fills left half of slide
  - "bottom_half": Image fills bottom half of slide
  - "center": Image centered on slide
  - "full": Image fills entire slide (background)

Example with preset:
{
  "slides": [
    {
      "slide_number": 5,
      "images": [
        {
          "path": "figures/diagram.png",
          "preset": "right_half"
        }
      ]
    }
  ]
}
"""

import argparse
import json
import os
import sys
from pathlib import Path

from pptx import Presentation
from pptx.util import Inches, Emu
from PIL import Image


def get_image_dimensions(image_path):
    """Get image dimensions in pixels."""
    with Image.open(image_path) as img:
        return img.size  # (width, height)


def calculate_position(preset, slide_width, slide_height, img_width, img_height):
    """
    Calculate position based on preset name.

    Returns (left, top, width, height) in inches.
    """
    margin = 0.25  # Small margin from edges

    if preset == "right_half":
        # Right half of slide, maintaining aspect ratio
        available_width = slide_width / 2 - margin * 2
        available_height = slide_height - margin * 2

        # Calculate size maintaining aspect ratio
        img_ratio = img_width / img_height
        available_ratio = available_width / available_height

        if img_ratio > available_ratio:
            # Image is wider, fit to width
            width = available_width
            height = width / img_ratio
        else:
            # Image is taller, fit to height
            height = available_height
            width = height * img_ratio

        left = slide_width / 2 + (slide_width / 2 - width) / 2
        top = (slide_height - height) / 2
        return left, top, width, height

    elif preset == "left_half":
        available_width = slide_width / 2 - margin * 2
        available_height = slide_height - margin * 2

        img_ratio = img_width / img_height
        available_ratio = available_width / available_height

        if img_ratio > available_ratio:
            width = available_width
            height = width / img_ratio
        else:
            height = available_height
            width = height * img_ratio

        left = margin + (slide_width / 2 - margin - width) / 2
        top = (slide_height - height) / 2
        return left, top, width, height

    elif preset == "bottom_half":
        available_width = slide_width - margin * 2
        available_height = slide_height / 2 - margin * 2

        img_ratio = img_width / img_height
        available_ratio = available_width / available_height

        if img_ratio > available_ratio:
            width = available_width
            height = width / img_ratio
        else:
            height = available_height
            width = height * img_ratio

        left = (slide_width - width) / 2
        top = slide_height / 2 + (slide_height / 2 - height) / 2
        return left, top, width, height

    elif preset == "center":
        # Center on slide, max 80% of dimensions
        max_width = slide_width * 0.8
        max_height = slide_height * 0.8

        img_ratio = img_width / img_height
        available_ratio = max_width / max_height

        if img_ratio > available_ratio:
            width = max_width
            height = width / img_ratio
        else:
            height = max_height
            width = height * img_ratio

        left = (slide_width - width) / 2
        top = (slide_height - height) / 2
        return left, top, width, height

    elif preset == "full":
        # Fill entire slide
        return 0, 0, slide_width, slide_height

    else:
        raise ValueError(f"Unknown preset: {preset}")


def insert_images(input_pptx, mapping_json, output_pptx, base_path=None):
    """
    Insert images into a PowerPoint presentation based on mapping.

    Args:
        input_pptx: Path to input PPTX file
        mapping_json: Path to JSON mapping file
        output_pptx: Path for output PPTX file
        base_path: Base path for resolving relative image paths
    """
    # Load presentation
    prs = Presentation(input_pptx)
    slide_width = prs.slide_width.inches if hasattr(prs.slide_width, 'inches') else prs.slide_width / 914400
    slide_height = prs.slide_height.inches if hasattr(prs.slide_height, 'inches') else prs.slide_height / 914400

    # Load mapping
    with open(mapping_json, 'r') as f:
        mapping = json.load(f)

    # Determine base path for images
    if base_path is None:
        base_path = Path(mapping_json).parent
    else:
        base_path = Path(base_path)

    # Process each slide mapping
    inserted_count = 0
    errors = []

    for slide_config in mapping.get('slides', []):
        slide_number = slide_config.get('slide_number')

        if slide_number is None:
            errors.append("Missing 'slide_number' in slide configuration")
            continue

        # Convert to 0-indexed
        slide_idx = slide_number - 1

        if slide_idx < 0 or slide_idx >= len(prs.slides):
            errors.append(f"Slide {slide_number} does not exist (presentation has {len(prs.slides)} slides)")
            continue

        slide = prs.slides[slide_idx]

        for img_config in slide_config.get('images', []):
            image_path = img_config.get('path')

            if not image_path:
                errors.append(f"Slide {slide_number}: Missing 'path' in image configuration")
                continue

            # Resolve image path
            full_path = base_path / image_path if not os.path.isabs(image_path) else Path(image_path)

            if not full_path.exists():
                errors.append(f"Slide {slide_number}: Image not found: {full_path}")
                continue

            try:
                # Get image dimensions for aspect ratio calculations
                img_width_px, img_height_px = get_image_dimensions(full_path)

                # Determine position and size
                if 'preset' in img_config:
                    left, top, width, height = calculate_position(
                        img_config['preset'],
                        slide_width,
                        slide_height,
                        img_width_px,
                        img_height_px
                    )
                else:
                    left = img_config.get('left', 0)
                    top = img_config.get('top', 0)
                    width = img_config.get('width')
                    height = img_config.get('height')

                    # Handle aspect ratio preservation
                    if width is None and height is None:
                        # Use original size (convert pixels to inches at 96 DPI)
                        width = img_width_px / 96
                        height = img_height_px / 96
                    elif width is None:
                        # Calculate width from height
                        ratio = img_width_px / img_height_px
                        width = height * ratio
                    elif height is None:
                        # Calculate height from width
                        ratio = img_height_px / img_width_px
                        height = width * ratio

                # Add the image
                slide.shapes.add_picture(
                    str(full_path),
                    Inches(left),
                    Inches(top),
                    Inches(width),
                    Inches(height)
                )

                inserted_count += 1
                print(f"  Slide {slide_number}: Inserted {image_path} at ({left:.2f}\", {top:.2f}\") size {width:.2f}\" x {height:.2f}\"")

            except Exception as e:
                errors.append(f"Slide {slide_number}: Error inserting {image_path}: {e}")

    # Report results
    print()
    print(f"Inserted {inserted_count} image(s)")

    if errors:
        print(f"\nErrors ({len(errors)}):")
        for error in errors:
            print(f"  - {error}")

    # Save output
    prs.save(output_pptx)
    print(f"\nSaved to: {output_pptx}")

    return len(errors) == 0


def main():
    parser = argparse.ArgumentParser(
        description="Insert images into PowerPoint slides based on a mapping JSON file",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Example image-mapping.json:
{
  "slides": [
    {
      "slide_number": 5,
      "images": [
        {
          "path": "figures/diagram.png",
          "preset": "right_half"
        }
      ]
    },
    {
      "slide_number": 10,
      "images": [
        {
          "path": "figures/screenshot.png",
          "left": 1.0,
          "top": 2.0,
          "width": 5.0,
          "height": null
        }
      ]
    }
  ]
}
        """
    )
    parser.add_argument("input_pptx", help="Path to input PowerPoint file")
    parser.add_argument("mapping_json", help="Path to image mapping JSON file")
    parser.add_argument("output_pptx", help="Path for output PowerPoint file")
    parser.add_argument("--base-path", "-b", help="Base path for resolving relative image paths")

    args = parser.parse_args()

    print(f"Input: {args.input_pptx}")
    print(f"Mapping: {args.mapping_json}")
    print(f"Output: {args.output_pptx}")
    print()

    success = insert_images(
        args.input_pptx,
        args.mapping_json,
        args.output_pptx,
        args.base_path
    )

    sys.exit(0 if success else 1)


if __name__ == "__main__":
    main()
